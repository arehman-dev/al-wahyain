// 2. Extract intro paragraphs from Ayah 1 of tafasir if available
function extractAyah1Intro(contentHtml) {
  if (!contentHtml) return '';
  const pRegex = /<p[^>]*>([\s\S]*?)<\/p>/gi;
  const introParas = [];
  const introKeywords = ['سورة', 'سورۃ', 'فضائل', 'فضیلت', 'نام', 'ربط', 'تعارف', 'مقدمہ', 'دیباچہ', 'مکی', 'مدنی', 'النزول', 'تسمیہ'];
  
  let m;
  while ((m = pRegex.exec(contentHtml)) !== null) {
    const rawP = m[1];
    const cleanText = rawP.replace(/<[^>]+>/g, '').trim();
    if (cleanText.length < 15) continue;
    
    // Check if this paragraph is part of the intro preamble
    if (introKeywords.some(k => cleanText.includes(k))) {
      introParas.push(rawP.trim());
    } else if (introParas.length > 0 && !cleanText.startsWith('آیت') && !cleanText.startsWith('1')) {
      introParas.push(rawP.trim());
      if (introParas.length >= 4) break;
    } else if (introParas.length > 0) {
      break;
    }
  }
  return introParas;
}

