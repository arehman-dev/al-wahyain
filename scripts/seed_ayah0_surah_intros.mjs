    'tayseer',
    'تیسیر القرآن',
    'مولانا عبدالرحمٰن کیلانی',
    s.id,
    0,
    0,
    `فضائل، خصوصیات و خلاصہ مضامین: سورة ${s.name_urdu}`,
    tayseerHtml,
    '[]',
    'مولانا عبدالرحمٰن کیلانیؒ - تیسیر القرآن',
    'https://www.equranlibrary.com'
